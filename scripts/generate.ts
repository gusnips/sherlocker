// Reads openapi.json and writes src/schema.d.ts, src/modules/*.ts and src/client.ts.
// Run it with `bun run generate`. Never edit the files it writes. openapi.json comes from
// `bun run spec`.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import ts from "typescript";

const HTTP_METHODS = ["get", "post", "patch"] as const;
type HttpMethod = (typeof HTTP_METHODS)[number];

function isHttpMethod(method: string): method is HttpMethod {
  return HTTP_METHODS.some((known) => known === method);
}

interface Parameter {
  $ref?: string;
  name?: string;
  in?: string;
  required?: boolean;
}

interface Operation {
  operationId: string;
  summary?: string;
  description?: string;
  deprecated?: boolean;
  parameters?: Parameter[];
  requestBody?: { content: Record<string, unknown> };
  responses: Record<string, { content?: Record<string, unknown> }>;
}

interface Doc {
  paths: Record<string, Partial<Record<HttpMethod, Operation>>>;
  components: { parameters?: Record<string, Parameter> };
}

const SPEC_FILE = "openapi.json";
const CLIENT_CLASS = "SherlockerClient";
const HEADER =
  "// Generated by scripts/generate.ts from openapi.json. Do not edit.\n";
const IDEMPOTENCY_HEADER = "Idempotency-Key";

// A whole sample answer is dozens of lines each. Short examples, like a CPF, stay.
function prune(key: string, value: unknown): unknown {
  if (
    (key === "example" || key === "examples") &&
    typeof value === "object" &&
    value !== null
  ) {
    return undefined;
  }
  return value;
}

// Sherlocker's descriptions use spaced em dashes. A comma reads the same.
const text = readFileSync(SPEC_FILE, "utf8").replaceAll(" \u2014 ", ", ");
const spec: OpenAPI3 = JSON.parse(text, prune);
const doc: Doc = JSON.parse(text, prune);

function words(name: string): string[] {
  return name.split(/[^a-zA-Z0-9]+/).filter(Boolean);
}

function pascalCase(name: string): string {
  return words(name)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
}

function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal[0].toLowerCase() + pascal.slice(1);
}

// ponytail: two words are the same when their first five letters match, so dossies finds
// getDossie, analyses finds createAnalysis and patentes finds Sherlocker's getPatentsByCpf.
// Upgrade path: a table of exceptions the first time this strips a word it should keep.
function sameWord(a: string, b: string): boolean {
  const [x, y] = [a.toLowerCase(), b.toLowerCase()];
  if (x.length < 4 || y.length < 4) return false;
  return x.slice(0, 5) === y.slice(0, 5);
}

// The group is the first word of the path: /pessoas/cpf/{cpf} is `pessoas`. The method is the
// operationId without the words of the group, because `pessoas.getPessoaByCpf` says it twice:
//   getPessoaByCpf  in pessoas  ->  getByCpf
//   getEmpregosByCpfPessoas  in pessoas  ->  getEmpregosByCpf
function nameOf(
  path: string,
  op: Operation,
): { group: string; method: string } {
  const segment = path.split("/")[1];
  const own = segment.split("-");
  const kept = (
    op.operationId.match(/[A-Z]?[a-z]+|[A-Z]+(?![a-z])|\d+/g) ?? []
  ).filter((token) => !own.some((word) => sameWord(token, word)));
  if (!kept.length)
    throw new Error(`${op.operationId} is only the name of its group.`);
  return { group: camelCase(segment), method: camelCase(kept.join(" ")) };
}

function docComment(op: Operation): string {
  const lines = [op.summary ?? ""];
  if (op.description && op.description !== op.summary)
    lines.push(op.description);
  if (op.deprecated)
    lines.push("@deprecated Sherlocker lists this endpoint as deprecated.");
  const body = lines.filter(Boolean).join("\n\n").replaceAll("*/", "*\\/");
  return `/**\n${body
    .split("\n")
    .map((line) => ` * ${line}`.trimEnd())
    .join("\n")}\n */`;
}

// `{dossie_id}` is the argument `dossieId` and the key "dossie_id".
function pathEntry(param: string): string {
  const arg = camelCase(param);
  return arg === param ? param : `${JSON.stringify(param)}: ${arg}`;
}

// The kind of body an endpoint takes, if any. JSON and file uploads are the only two Sherlocker has.
function bodyKind({ path, method, op }: Endpoint): "json" | "form" | undefined {
  const types = Object.keys(op.requestBody?.content ?? {});
  if (!types.length) return undefined;
  if (types.length === 1 && types[0] === "application/json") return "json";
  if (types.length === 1 && types[0] === "multipart/form-data") return "form";
  throw new Error(
    `${method} ${path} sends ${types.join(", ")}, which this script does not render.`,
  );
}

function answersJson(op: Operation): boolean {
  return Object.entries(op.responses).some(
    ([status, response]) =>
      status.startsWith("2") && response.content?.["application/json"],
  );
}

function resolve(param: Parameter): Parameter {
  if (!param.$ref) return param;
  const name = param.$ref.split("/").pop() ?? "";
  const found = doc.components.parameters?.[name];
  if (!found) throw new Error(`No parameter ${param.$ref} in ${SPEC_FILE}.`);
  return found;
}

interface Endpoint {
  name: string;
  path: string;
  method: HttpMethod;
  op: Operation;
}

const groups = new Map<string, Endpoint[]>();
for (const [path, item] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!isHttpMethod(method)) {
      throw new Error(
        `${method.toUpperCase()} ${path} is a method this script does not render.`,
      );
    }
    const { group, method: name } = nameOf(path, op);
    const endpoints = groups.get(group) ?? [];
    if (endpoints.some((endpoint) => endpoint.name === name)) {
      throw new Error(
        `Two operations in "${group}" are named "${name}". Change nameOf to tell them apart.`,
      );
    }
    endpoints.push({ name, path, method, op });
    groups.set(group, endpoints);
  }
}

// The path parameters are positional, in the order they appear in the URL, so
// `pessoas.getEnderecosByCpf(cpf, { limit: 10 })` reads like the URL.
function renderMethod(endpoint: Endpoint): string {
  const { name, path, method, op } = endpoint;
  const params = (op.parameters ?? []).map(resolve);
  const inPath = [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
  const query = params.filter((param) => param.in === "query");
  const needsKey = params.some(
    (param) => param.name === IDEMPOTENCY_HEADER && param.required,
  );
  if (needsKey && query.length) {
    throw new Error(
      `${method} ${path} needs an idempotency key and has a query: the options argument cannot be last and required.`,
    );
  }

  const type = `"${path}", "${method}"`;
  const args = inPath.map(
    (param) => `${camelCase(param)}: PathParams<${type}>["${param}"]`,
  );
  const send: string[] = [];
  if (inPath.length) {
    send.push(`path: { ${inPath.map(pathEntry).join(", ")} }`);
  }
  if (query.length) {
    const optional = query.some((param) => param.required) ? "" : "?";
    args.push(`query${optional}: Query<${type}>`);
    send.push("query");
  }
  const body = bodyKind(endpoint);
  if (body) {
    args.push(`body: Body<${type}>`);
    send.push(body === "form" ? "form: body" : "json: body");
  }
  args.push(
    needsKey
      ? "options: CallOptions & { idempotencyKey: string }"
      : "options?: CallOptions",
  );

  const call = answersJson(op) ? "send" : "download";
  return `${docComment(op)}\n${name}(${args.join(", ")}) {\n  return this.http.${call}("${method}", "${path}", { ${send.join(", ")} }, options);\n}`;
}

function renderModule(group: string, endpoints: Endpoint[]): string {
  const source = endpoints.map(renderMethod).join("\n\n");
  const names = ["Body", "CallOptions", "PathParams", "Query"].filter((name) =>
    new RegExp(`\\b${name}\\b`).test(source),
  );
  return `${HEADER}import { ${[...names, "Transport"].map((name) => `type ${name}`).join(", ")} } from "../http";

export class ${pascalCase(group)}Module {
  constructor(private readonly http: Transport) {}

${source}
}
`;
}

function renderClient(groupNames: string[]): string {
  const modules = groupNames.map((name) => ({
    name,
    className: `${pascalCase(name)}Module`,
  }));
  return `${HEADER}import { Transport, type SherlockerConfig } from "./http";
${modules.map(({ name, className }) => `import { ${className} } from "./modules/${name}";`).join("\n")}

export class ${CLIENT_CLASS} {
${modules.map(({ name, className }) => `  readonly ${name}: ${className};`).join("\n")}

  constructor(config: SherlockerConfig | string) {
    const http = new Transport(typeof config === "string" ? { token: config } : config);
${modules.map(({ name, className }) => `    this.${name} = new ${className}(http);`).join("\n")}
  }
}
`;
}

// A file field is a Blob (a File is one), not the string openapi-typescript writes for "binary".
const types = await openapiTS(spec, {
  transform: (schema) =>
    schema.format === "binary"
      ? ts.factory.createTypeReferenceNode("Blob")
      : undefined,
});

rmSync("src/modules", { recursive: true, force: true });
mkdirSync("src/modules", { recursive: true });
writeFileSync("src/schema.d.ts", astToString(types));
for (const [group, endpoints] of groups) {
  writeFileSync(`src/modules/${group}.ts`, renderModule(group, endpoints));
}
writeFileSync("src/client.ts", renderClient([...groups.keys()]));
console.log(
  [...groups]
    .map(([group, endpoints]) => `${group}: ${endpoints.length}`)
    .join(", "),
);
